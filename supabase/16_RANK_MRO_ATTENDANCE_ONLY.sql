-- DAG Esports: attendance-only Rank and MLBB Rising Open (MRO) entries
-- APPLY IN SUPABASE SQL EDITOR BEFORE using the new Match Log selections.
-- Additive migration: existing matches, evaluations and KPI scores are unchanged.
begin;

do $preflight$
begin
  if to_regclass('public.players') is null
    or to_regprocedure('public.can_manage_dag(text)') is null then
    raise exception 'DAG players and management security migrations must exist first.';
  end if;
end
$preflight$;

create table if not exists public.attendance_only_activities (
  id bigint generated by default as identity primary key,
  team text not null,
  activity_type text not null
    constraint dag_attendance_activity_type_check check (
      activity_type in ('Rank', 'MLBB Rising Open (MRO)')
    ),
  activity_date date not null,
  result_screenshots text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.attendance_only_activity_members (
  activity_id bigint not null references public.attendance_only_activities(id) on delete cascade,
  member_id bigint not null,
  ign_snapshot text not null,
  status text not null constraint dag_attendance_only_status_check
    check (status in ('present', 'absent')),
  primary key (activity_id, member_id)
);

create index if not exists dag_attendance_activities_team_date
  on public.attendance_only_activities(team, activity_date desc, id desc);

alter table public.attendance_only_activities enable row level security;
alter table public.attendance_only_activity_members enable row level security;

-- Read through management only. All writes go through validated transactional RPCs.
revoke all on public.attendance_only_activities from public, anon, authenticated;
revoke all on public.attendance_only_activity_members from public, anon, authenticated;
grant select on public.attendance_only_activities to authenticated;
grant select on public.attendance_only_activity_members to authenticated;

create policy dag_attendance_only_activities_read on public.attendance_only_activities
  for select to authenticated
  using ((select public.can_manage_dag('edit_matches')));

create policy dag_attendance_only_members_read on public.attendance_only_activity_members
  for select to authenticated
  using ((select public.can_manage_dag('edit_matches')));

create or replace function public.save_attendance_only_activity(
  p_activity_id bigint,
  p_team text,
  p_activity_type text,
  p_activity_date date,
  p_screenshots text,
  p_attendance jsonb
) returns bigint
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_id bigint;
  v_roster_count integer;
  v_attendance_count integer;
  v_unique_count integer;
begin
  if auth.uid() is null or not public.can_manage_dag('edit_matches') then
    raise exception 'Not authorized to manage attendance activities.';
  end if;

  if p_team is null or btrim(p_team) = ''
     or p_activity_type not in ('Rank', 'MLBB Rising Open (MRO)')
     or p_activity_date is null then
    raise exception 'Team, permitted activity type and date are required.';
  end if;

  if jsonb_typeof(p_attendance) is distinct from 'array' then
    raise exception 'Attendance must be an array of player IDs and statuses.';
  end if;

  select count(*) into v_roster_count
    from public.players
    where team = p_team;

  select count(*), count(distinct a.member_id)
    into v_attendance_count, v_unique_count
    from jsonb_to_recordset(p_attendance) as a(member_id bigint, status text);

  if v_roster_count = 0 or v_attendance_count <> v_roster_count
     or v_unique_count <> v_roster_count then
    raise exception 'Please record Present or Absent for every current team member.';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(p_attendance) as a(member_id bigint, status text)
    left join public.players as p on p.id = a.member_id and p.team = p_team
    where p.id is null or a.status is null
       or a.status not in ('present', 'absent')
  ) then
    raise exception 'Invalid team member or attendance status.';
  end if;

  if p_activity_id is null then
    insert into public.attendance_only_activities
      (team, activity_type, activity_date, result_screenshots)
    values
      (p_team, p_activity_type, p_activity_date, nullif(btrim(p_screenshots), ''))
    returning id into v_id;
  else
    update public.attendance_only_activities
    set activity_type = p_activity_type,
        activity_date = p_activity_date,
        result_screenshots = nullif(btrim(p_screenshots), ''),
        updated_at = now()
    where id = p_activity_id and team = p_team
    returning id into v_id;

    if v_id is null then
      raise exception 'Activity not found in selected team.';
    end if;

    delete from public.attendance_only_activity_members
      where activity_id = v_id;
  end if;

  insert into public.attendance_only_activity_members
    (activity_id, member_id, ign_snapshot, status)
  select v_id, p.id, p.ign, a.status
  from jsonb_to_recordset(p_attendance) as a(member_id bigint, status text)
  join public.players as p on p.id = a.member_id and p.team = p_team;

  return v_id;
end
$function$;

create or replace function public.remove_attendance_only_activity(
  p_activity_id bigint,
  p_team text
) returns boolean
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_id bigint;
begin
  if auth.uid() is null or not public.can_manage_dag('delete_matches') then
    raise exception 'Only an owner or manager may delete attendance activities.';
  end if;

  delete from public.attendance_only_activities
  where id = p_activity_id and team = p_team
  returning id into v_id;
  return v_id is not null;
end
$function$;

revoke all on function public.save_attendance_only_activity(bigint,text,text,date,text,jsonb)
  from public, anon;
revoke all on function public.remove_attendance_only_activity(bigint,text)
  from public, anon;
grant execute on function public.save_attendance_only_activity(bigint,text,text,date,text,jsonb)
  to authenticated;
grant execute on function public.remove_attendance_only_activity(bigint,text)
  to authenticated;

commit;
notify pgrst, 'reload schema';
