-- DAG Esports: Weekly Player Improvement Targets
-- Run in the existing Supabase SQL Editor as postgres BEFORE testing the preview.
-- New table only. Existing players/matches/reports/RLS policies are left unchanged.
-- Back up before running migrations in production.
begin;

do $$
begin
  if to_regclass('public.players') is null or to_regprocedure('public.can_manage_dag(text)') is null
    or to_regclass('public.public_player_profiles') is null then
    raise exception 'DAG security baseline (players, safe view and permissions) is required.';
  end if;
end $$;

create table if not exists public.weekly_player_targets (
  id bigint generated by default as identity primary key,
  player_id bigint not null references public.players(id) on delete cascade,
  team text not null,
  week_start date not null,
  metric_key text not null,
  target_score numeric(2,1) not null,
  focus_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint dag_target_unique_per_metric unique (player_id, week_start, metric_key),
  constraint dag_target_monday check (extract(isodow from week_start) = 1),
  constraint dag_target_score_range check (target_score >= 1 and target_score <= 5),
  constraint dag_target_metric check (metric_key in (
    'mechanics_score', 'macro_score', 'communication_score',
    'role_execution_score', 'discipline_score', 'hero_pool_score'
  )),
  constraint dag_target_focus_length check (focus_note is null or char_length(focus_note) <= 300)
);

create index if not exists dag_targets_team_week_idx
  on public.weekly_player_targets (team, week_start desc, player_id);

alter table public.weekly_player_targets enable row level security;
revoke all on public.weekly_player_targets from public, anon, authenticated;
grant select on public.weekly_player_targets to anon, authenticated;
grant insert, update, delete on public.weekly_player_targets to authenticated;
-- Identity sequences need USAGE to insert rows as authenticated users.
grant usage, select on sequence public.weekly_player_targets_id_seq to authenticated;

-- Targets are deliberately public: they appear alongside published KPI graphs
-- and weekly coach reports. Coaches must not enter sensitive personal details.
create policy dag_targets_public_read on public.weekly_player_targets
  for select to anon, authenticated using (true);

create policy dag_targets_insert on public.weekly_player_targets
  for insert to authenticated
  with check (
    (select public.can_manage_dag('edit_reports')) and
    exists (
      select 1 from public.public_player_profiles p
      where p.id = player_id and p.team = weekly_player_targets.team
        and lower(coalesce(p.role, '')) not in ('coach', 'manager')
    )
  );

create policy dag_targets_update on public.weekly_player_targets
  for update to authenticated
  using ((select public.can_manage_dag('edit_reports')))
  with check (
    (select public.can_manage_dag('edit_reports')) and
    exists (
      select 1 from public.public_player_profiles p
      where p.id = player_id and p.team = weekly_player_targets.team
        and lower(coalesce(p.role, '')) not in ('coach', 'manager')
    )
  );

create policy dag_targets_delete on public.weekly_player_targets
  for delete to authenticated
  using ((select public.can_manage_dag('edit_reports')));

commit;
notify pgrst, 'reload schema';

-- Verify the table and RLS status (read-only).
select table_name, rowsecurity as rls_enabled
from (select 'weekly_player_targets'::text as table_name, relrowsecurity as rowsecurity
      from pg_class where oid = 'public.weekly_player_targets'::regclass) t;
